"""Ledger ports."""

from datetime import date
from typing import Protocol

from app.shared.domain.models import LedgerEntry


class LedgerRepository(Protocol):
    def is_empty(self) -> bool: ...

    def all_entries(self) -> list[LedgerEntry]: ...

    def find_invoice(self, nit: str, document_number: str) -> str | None: ...

    def last_sequence(self) -> int: ...

    def append(self, entry: LedgerEntry, sequence: int) -> None: ...

    def get(self, filing_number: str) -> LedgerEntry | None: ...

    def update(self, entry: LedgerEntry) -> None: ...

    def due_between(self, start: date, end: date) -> list[LedgerEntry]: ...


class LedgerWorkbook(Protocol):
    """The client's Excel file: the format Accounting and Legal already use."""

    def read(self) -> list[LedgerEntry]: ...

    def render(self, entries: list[LedgerEntry]) -> bytes: ...

    def save(self, entries: list[LedgerEntry]) -> None: ...

    def file_bytes(self) -> bytes: ...


class SyncedWorkbook(Protocol):
    """The shared Excel as a table people also edit (versioned reads, guarded atomic writes)."""

    headers: list[str]

    def read_table(self): ...  # -> WorkbookTable(rows: dict[filing_number, cells], version)

    def write_table(
        self, updates: dict[str, list[str]], appends: list[list[str]], expected_version: str
    ) -> str: ...

    def render_cells(self, entry: LedgerEntry) -> list[str]: ...

    def absorb(self, entry: LedgerEntry, cells: list[str]) -> LedgerEntry: ...

    def parse(self, cells: list[str]) -> LedgerEntry: ...

    def file_bytes(self) -> bytes: ...


class SyncStore(Protocol):
    """What Docket last wrote for each row (the merge base) and the last sync outcome."""

    def bases(self) -> dict[str, list[str]]: ...

    def set_bases(self, bases: dict[str, list[str]]) -> None: ...

    def state(self) -> dict | None: ...

    def set_state(self, state: dict) -> None: ...
